// Command samplestores converts upstream openfga/sample-stores store files
// into ofga model-test workspaces. It is a dev tool: it reads only -src and
// never touches the network.
//
//	go run ./tools/samplestores -src <sample-stores>/stores -out internal/sandbox/samples \
//	    -stores github,gdrive -commit <sha>
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "samplestores:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	fs := flag.NewFlagSet("samplestores", flag.ContinueOnError)
	src := fs.String("src", "", "path to the sample-stores `stores` directory")
	out := fs.String("out", "", "output directory")
	stores := fs.String("stores", "", "comma-separated store names")
	commit := fs.String("commit", "", "upstream commit recorded in generated headers")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *src == "" || *out == "" || *stores == "" {
		return fmt.Errorf("-src, -out and -stores are required")
	}
	for _, name := range strings.Split(*stores, ",") {
		name = strings.TrimSpace(name)
		dir := filepath.Join(*src, name)
		b, err := os.ReadFile(filepath.Join(dir, "store.fga.yaml"))
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		ws, err := ConvertNamed(name, b, func(rel string) ([]byte, error) {
			return os.ReadFile(filepath.Join(dir, rel))
		})
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if err := writeWorkspace(filepath.Join(*out, name), name, ws, *commit); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
	}
	return nil
}

// writeWorkspace writes ws under dir, prefixing every file with the
// generated-file header.
func writeWorkspace(dir, name string, ws Workspace, commit string) error {
	header := fmt.Sprintf("# Generated by tools/samplestores from openfga/sample-stores@%s (Apache-2.0). Do not edit.\n", commit)
	files := map[string][]byte{
		"ofga.yaml":                    ws.Manifest,
		"model.fga":                    ws.Model,
		"fixtures/" + name + ".yaml":   ws.Fixture,
		"tests/" + name + ".test.yaml": ws.Tests,
	}
	for rel, body := range files {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, append([]byte(header), body...), 0o644); err != nil {
			return err
		}
	}
	return nil
}
